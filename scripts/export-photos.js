// Publishes the player photo list for the live site: writes vercel-deploy/data/photos.json with each
// photo's original address and credit (no image files). Only WTA and ESPN headshots and Wikimedia
// Commons images are included. Commit the file and push to update the live site.
//   npm run export-photos
const fs = require("fs");
const path = require("path");
const { backfillUrls, publicPhotos } = require("../lib/photos");

const OUT = path.join(__dirname, "..", "vercel-deploy", "data", "photos.json");

(async () => {
  await backfillUrls((n, total, name, ok) => console.log(`  address [${n}/${total}] ${ok ? "found" : "none "}  ${name}`));
  const photos = publicPhotos();
  fs.writeFileSync(OUT, JSON.stringify({
    _help: "Generated by npm run export-photos: each player's photo address (WTA, ESPN or Wikimedia Commons) and credit, loaded by the live site from the original host.",
    photos,
  }, null, 1) + "\n");
  const by = {};
  for (const p of Object.values(photos)) { const s = p.src.includes("wtatennis") ? "WTA" : p.src.includes("espncdn") ? "ESPN" : "Wikimedia Commons"; by[s] = (by[s] || 0) + 1; }
  console.log(`\nWrote ${Object.keys(photos).length} photos to vercel-deploy/data/photos.json:`, by);
})().catch((e) => { console.error(e); process.exit(1); });
